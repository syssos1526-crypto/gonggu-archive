-- =============================================================================
-- 공구 아카이브 — Auth/관심 기능에 필요한 최소 GRANT
-- =============================================================================
-- 스키마, unique 제약, RLS 정책, 가입 트리거는 이미 올바르게 구성되어 있음을
-- 진단으로 확인했습니다. 유일하게 빠진 것은 `authenticated` 역할의 테이블
-- 단위 GRANT뿐입니다 (RLS는 "이미 권한이 있는 역할"이 볼 수 있는 행을 더
-- 좁히는 필터일 뿐, 그 자체로 접근 권한을 주지는 않습니다).
--
-- 이 파일은 실행하지 않았습니다. Supabase 대시보드 SQL Editor에서 직접
-- 실행해 주세요. anon에는 아무 권한도 추가하지 않습니다(로그인 사용자 전용
-- 기능이므로 의도적으로 최소화).
-- =============================================================================

-- users: 본인 행 조회/수정 (RLS가 본인 행으로 이미 제한)
grant select, update on public.users to authenticated;

-- interests: 본인 행 조회/추가/삭제 (관심 등록·해제, 마이페이지 목록용)
grant select, insert, delete on public.interests to authenticated;
